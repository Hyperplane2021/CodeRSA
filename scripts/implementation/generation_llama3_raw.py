generation_params = SamplingParams(n = 20,
                temperature=1.0,
                max_tokens = 1024,)



# 遍历每个问题数据
for question in tqdm(data_02, desc="Processing Questions"):
    task_id, task_prompt, test_cases = get_information(question, dataset)
    function_name = extract_function_name(task_prompt)

    # 重复生成 10 次
    for _ in range(10):
        response = llm.generate('###Code Start###\n'+task_prompt, generation_params)

        # 遍历每个候选输出
        for candidate in response[0].outputs:
            try:
                function = extract_function(response[0].prompt + candidate.text)
            except Exception as e:
                print(f"Failed to extract function for {task_id}: {e}")
                continue

            # 获取新的 Function_id
            if question['output'] == []:
              idx = 0
            else:
              idx = int(question['output'][-1]['Function_id'].split('_')[-1]) + 1
            # 将新生成的函数添加到输出列表
            question['output'].append({
                'Function_id': f'{function_name}_{idx:02d}',
                'Function': function,
                'tokens_logprob': 0.42,
            })

