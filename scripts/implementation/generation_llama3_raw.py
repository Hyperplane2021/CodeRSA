def extract_function(content):
    # 确保字符串以###Code Start###开头并包含###Code End###或### Code End ###
    start_marker = "###Code Start###\n"
    end_markers = ["###Code End###", "### Code End ###"]

    if not content.startswith(start_marker):
        raise ValueError("字符串必须以'###Code Start###\\n'开头。")

    # 找到结束标记的位置
    end_index = -1
    for marker in end_markers:
        end_index = content.find(marker)
        if end_index != -1:
            break

    if end_index == -1:
        raise ValueError("字符串中缺少结束标记 '###Code End###' 或 '### Code End ###'。")

    # 分割内容为行
    lines = content[len(start_marker):end_index].strip().split('\n')

    # 用于匹配前面至少有两个空格的 return 行的正则表达式
    pattern = re.compile(r'^[ ]{2,}return')
    last_return_index = None

    # 在结束标记行之前查找最后一行满足要求的 return
    for i in range(len(lines)):
        if pattern.search(lines[i]):
            last_return_index = i

    if last_return_index is None:
        # 若在结束标记前找不到满足条件的 return，则根据需要处理
        return ""

    # 提取从开头到最后那个 return 行（包含该行）的内容
    result = '\n'.join(lines[:last_return_index + 1])
    return result

