def extract_function(code_str: str) -> str:
    # 搜索包含 return 语句的那一行，并返回从开头到该行结束的内容
    match = re.search(r'  \breturn\b.*\n', code_str)
    if match:
        return code_str[:match.end()]  # 提取从开头到 return 那行结束的内容
