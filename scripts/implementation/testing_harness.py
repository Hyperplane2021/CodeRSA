def run_single_test_case(func_str, test_case):
    """
    单进程执行某个测试用例，并在3秒内超时。
    """
    local_env = {
        "re": re,
        "typing": typing,
        "List": typing.List,
        "Tuple": typing.Tuple,
        "prod": math.prod,
    }
    exec(func_str, local_env)
    func_name = list(local_env.keys())[-1]

    test_code = compile(test_case, '<string>', 'exec')
    exec(test_code, local_env)
    return True, None


def test_function_with_signal(func_str, test_cases):
    passed_tests = 0
    errors = []
    global_env = {}

    # 先测试编译函数定义
    try:
        exec(func_str, global_env)
    except Exception as e:
        return 0.0, [f"Function definition error: {str(e)}"]

    func_name = list(global_env.keys())[-1]
    modified_test_cases = format_test(test_cases, func_name)
    total_tests = len(modified_test_cases)

    for case in modified_test_cases:
        try:
            success, error = run_single_test_case(func_str, case)
            if success:
                passed_tests += 1
            else:
                errors.append(error)
        except TimeoutError:
            errors.append(f"Test case error: {case}, Error: run out of time")
        except AssertionError:
            errors.append("Some Test Failed")
        except Exception as e:
            errors.append(f"Test case error: {case}, Exception: {str(e)}")

    pass_rate = round((passed_tests / total_tests) * 100, 2) if total_tests > 0 else 0.0
    if passed_tests == total_tests:
        errors.append("pass")

    return pass_rate, errors

