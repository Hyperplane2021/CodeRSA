def format_test(test_cases, func_name):
    """
    将 test_cases（可以是包含 check(...) 的完整代码字符串，或已经提取好的列表）
    中的 assert 语句提取出来，并把 'candidate' 替换为 func_name。
    返回一个测试用例字符串列表。
    """
    # 如果传进来的是单个字符串，就先拆成行
    if isinstance(test_cases, str):
        lines = test_cases.splitlines()
    else:
        # 假设是可迭代的字符串列表，逐行收集
        lines = []
        for item in test_cases:
            if isinstance(item, str):
                lines.extend(item.splitlines())

    cases = []
    in_check = False
    for line in lines:
        # 找到 def check(candidate):
        if re.match(r'\s*def\s+check\s*\(\s*candidate\s*\)\s*:', line):
            in_check = True
            continue
        if in_check:
            # 如果又遇到下一个 def，则说明 check 体结束
            if re.match(r'\s*def\s+\w+\s*\(', line):
                break
            # 匹配 assert 语句
            m = re.match(r'\s*assert\s+(.+)', line)
            if m:
                expr = m.group(1)
                # 替换 candidate 为真实函数名
                expr = re.sub(r'\bcandidate\b', func_name, expr)
                cases.append('assert ' + expr)
    return cases


