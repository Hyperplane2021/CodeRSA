def timeout(seconds=2, error_message="Timeout"):
    """
    Decorator to raise TimeoutError if function runs more than `seconds`.
    Only works reliably on Unix-based systems.
    """
    def decorator(func):
        def _handle_timeout(signum, frame):
            raise TimeoutError(error_message)

        @functools.wraps(func)
        def wrapper(*args, **kwargs):
            # 设置信号处理器
            signal.signal(signal.SIGALRM, _handle_timeout)
            # 启动闹钟
            signal.alarm(seconds)
            try:
                result = func(*args, **kwargs)
            finally:
                # 关闭闹钟
                signal.alarm(0)
            return result
        return wrapper
    return decorator

